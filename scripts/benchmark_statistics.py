#!/usr/bin/env python
"""
Benchmark Statistics Calculator

This script reads a benchmark CSV file generated by main_benchmark_rag_result.py
and calculates:
1. Average score
2. Score distribution (counts and percentages)
3. List of all errors with their query IDs

Usage:
    python scripts/benchmark_statistics.py --input-csv <path_to_benchmark_csv>

Example:
    python scripts/benchmark_statistics.py --input-csv ./output/benchmark-Linq-AI-Research_FinDER-index-solution-Linq-AI-Research_FinDER-300-02-20260130_122232.csv
"""

import argparse
import csv
import sys
from collections import Counter
from pathlib import Path
from typing import Dict, List, Optional, Tuple


def parse_arguments():
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description='Calculate statistics from benchmark CSV file',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog='''
Examples:
    python scripts/benchmark_statistics.py --input-csv ./output/benchmark.csv
    python scripts/benchmark_statistics.py -i ./output/benchmark.csv

Input CSV Expected Columns:
    original_row, query_id, query, rag_answer, ground_truth, score, evaluation_error
        '''
    )
    
    parser.add_argument(
        '--input-csv', '-i',
        type=str,
        required=True,
        metavar='PATH',
        help='Path to the benchmark CSV file'
    )
    
    return parser.parse_args()


def load_benchmark_results(csv_path: str) -> List[Dict[str, str]]:
    """
    Load benchmark results from a CSV file.
    
    Args:
        csv_path: Path to the CSV file
        
    Returns:
        List of dictionaries, each representing a row
    """
    results = []
    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            results.append(dict(row))
    return results


def calculate_average_score(results: List[Dict[str, str]]) -> Tuple[Optional[float], int, int]:
    """
    Calculate the average score from benchmark results.
    
    Args:
        results: List of benchmark result dictionaries
        
    Returns:
        Tuple of (average_score, valid_count, total_count)
    """
    valid_scores = []
    for r in results:
        score_str = r.get('score', '').strip()
        if score_str:
            try:
                score = int(score_str)
                valid_scores.append(score)
            except ValueError:
                pass
    
    total_count = len(results)
    valid_count = len(valid_scores)
    
    if not valid_scores:
        return None, valid_count, total_count
    
    return sum(valid_scores) / len(valid_scores), valid_count, total_count


def calculate_score_distribution(results: List[Dict[str, str]]) -> Dict[int, int]:
    """
    Calculate the distribution of scores (1-10).
    
    Args:
        results: List of benchmark result dictionaries
        
    Returns:
        Dictionary mapping score -> count
    """
    scores = []
    for r in results:
        score_str = r.get('score', '').strip()
        if score_str:
            try:
                score = int(score_str)
                scores.append(score)
            except ValueError:
                pass
    
    return dict(Counter(scores))


def get_errors_with_ids(results: List[Dict[str, str]]) -> List[Tuple[str, str, str]]:
    """
    Get all entries with evaluation errors.
    
    Args:
        results: List of benchmark result dictionaries
        
    Returns:
        List of tuples (query_id, original_row, error_message)
    """
    errors = []
    for r in results:
        error = r.get('evaluation_error', '').strip()
        if error:
            query_id = r.get('query_id', 'N/A')
            original_row = r.get('original_row', 'N/A')
            errors.append((query_id, original_row, error))
    return errors


def print_statistics(csv_path: str, results: List[Dict[str, str]]):
    """
    Print all statistics to stdout.
    
    Args:
        csv_path: Path to the CSV file (for display)
        results: List of benchmark result dictionaries
    """
    print("=" * 80)
    print("BENCHMARK STATISTICS")
    print("=" * 80)
    print(f"Input file: {csv_path}")
    print(f"Total rows: {len(results)}")
    print()
    
    # 1. Average Score
    print("-" * 80)
    print("1. AVERAGE SCORE")
    print("-" * 80)
    avg_score, valid_count, total_count = calculate_average_score(results)
    
    if avg_score is not None:
        print(f"Average Score: {avg_score:.2f} / 10")
        print(f"Valid scores: {valid_count} / {total_count}")
    else:
        print("Average Score: N/A (no valid scores found)")
    print()
    
    # 2. Score Distribution
    print("-" * 80)
    print("2. SCORE DISTRIBUTION")
    print("-" * 80)
    distribution = calculate_score_distribution(results)
    
    if distribution:
        # Calculate percentages
        total_valid = sum(distribution.values())
        
        # Print header
        print(f"{'Score':<8} {'Count':<8} {'Percentage':<12} {'Bar'}")
        print("-" * 60)
        
        # Print distribution for all scores 1-10
        for score in range(1, 11):
            count = distribution.get(score, 0)
            percentage = (count / total_valid * 100) if total_valid > 0 else 0
            bar = "#" * int(percentage / 2)  # Scale bar to max 50 chars
            print(f"{score:<8} {count:<8} {percentage:>6.1f}%     {bar}")
        
        print("-" * 60)
        print(f"Total: {total_valid} scored entries")
        
        # Additional statistics
        if distribution:
            scores = []
            for score, count in distribution.items():
                scores.extend([score] * count)
            
            if scores:
                print(f"\nMin Score: {min(scores)}")
                print(f"Max Score: {max(scores)}")
                
                # Median calculation
                sorted_scores = sorted(scores)
                n = len(sorted_scores)
                if n % 2 == 0:
                    median = (sorted_scores[n//2 - 1] + sorted_scores[n//2]) / 2
                else:
                    median = sorted_scores[n//2]
                print(f"Median Score: {median:.1f}")
                
                # Standard deviation
                if len(scores) > 1:
                    mean = sum(scores) / len(scores)
                    variance = sum((x - mean) ** 2 for x in scores) / len(scores)
                    std_dev = variance ** 0.5
                    print(f"Std Dev: {std_dev:.2f}")
    else:
        print("No valid scores found in the data.")
    print()
    
    # 3. Errors List
    print("-" * 80)
    print("3. ERRORS LIST")
    print("-" * 80)
    errors = get_errors_with_ids(results)
    
    if errors:
        print(f"Total errors: {len(errors)}")
        print()
        print(f"{'Query ID':<12} {'Row':<8} {'Error Message'}")
        print("-" * 60)
        for query_id, original_row, error in errors:
            # Truncate long error messages for display
            error_display = error[:50] + "..." if len(error) > 50 else error
            print(f"{query_id:<12} {original_row:<8} {error_display}")
    else:
        print("No errors found. All evaluations completed successfully!")
    
    print()
    print("=" * 80)


def main():
    """Main entry point."""
    args = parse_arguments()
    
    # Validate input file exists
    csv_path = Path(args.input_csv)
    if not csv_path.exists():
        print(f"Error: Input CSV file does not exist: {args.input_csv}", file=sys.stderr)
        sys.exit(1)
    
    # Load results
    try:
        results = load_benchmark_results(args.input_csv)
    except Exception as e:
        print(f"Error loading CSV file: {e}", file=sys.stderr)
        sys.exit(1)
    
    if not results:
        print("Error: No data found in CSV file", file=sys.stderr)
        sys.exit(1)
    
    # Print statistics
    print_statistics(args.input_csv, results)


if __name__ == "__main__":
    main()
