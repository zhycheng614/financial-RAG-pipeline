#!/usr/bin/env python
"""
Query Result Error Analysis

This script reads a query-answer CSV file generated by the RAG pipeline
and lists all query_id-error pairs.

Usage:
    python scripts/query_result_error_analysis.py --input-csv <path_to_csv>

Example:
    python scripts/query_result_error_analysis.py --input-csv ./output/Linq-AI-Research_FinDER-300-01-1-to-300-gpt-4.1-20260121_160659.csv
"""

import argparse
import csv
import sys
from collections import Counter
from pathlib import Path
from typing import Dict, List, Tuple


def parse_arguments():
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description='Analyze errors in query result CSV files',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog='''
Examples:
    python scripts/query_result_error_analysis.py --input-csv ./output/results.csv
    python scripts/query_result_error_analysis.py -i ./output/results.csv

Input CSV Expected Columns:
    original_row, query_id, query, tickers, file_paths, missing_files, final_answer, error
        '''
    )
    
    parser.add_argument(
        '--input-csv', '-i',
        type=str,
        required=True,
        metavar='PATH',
        help='Path to the query result CSV file'
    )
    
    return parser.parse_args()


def load_query_results(csv_path: str) -> List[Dict[str, str]]:
    """
    Load query results from a CSV file.
    
    Args:
        csv_path: Path to the CSV file
        
    Returns:
        List of dictionaries, each representing a row
    """
    results = []
    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            results.append(dict(row))
    return results


def get_errors_with_ids(results: List[Dict[str, str]]) -> List[Tuple[str, str, str, str]]:
    """
    Get all entries with errors.
    
    Args:
        results: List of query result dictionaries
        
    Returns:
        List of tuples (query_id, original_row, error_message, query)
    """
    errors = []
    for r in results:
        error = r.get('error', '').strip()
        if error:
            query_id = r.get('query_id', 'N/A')
            original_row = r.get('original_row', 'N/A')
            query = r.get('query', 'N/A')
            errors.append((query_id, original_row, error, query))
    return errors


def categorize_errors(errors: List[Tuple[str, str, str, str]]) -> Dict[str, List[Tuple[str, str, str]]]:
    """
    Categorize errors by error type/message pattern.
    
    Args:
        errors: List of (query_id, original_row, error_message, query) tuples
        
    Returns:
        Dictionary mapping error category to list of (query_id, original_row, query) tuples
    """
    categories = {}
    
    for query_id, original_row, error, query in errors:
        # Normalize error message to create category
        error_lower = error.lower()
        
        if "no ticker" in error_lower or "no files found for tickers" in error_lower:
            category = "No files found for tickers"
        elif "no financial report" in error_lower:
            category = "No financial report files found"
        elif "no ticker symbols extracted" in error_lower:
            category = "No ticker symbols extracted"
        elif "timeout" in error_lower:
            category = "Timeout"
        elif "api" in error_lower or "rate limit" in error_lower:
            category = "API/Rate limit error"
        else:
            category = "Other"
        
        if category not in categories:
            categories[category] = []
        categories[category].append((query_id, original_row, query, error))
    
    return categories


def print_error_analysis(csv_path: str, results: List[Dict[str, str]]):
    """
    Print error analysis to stdout.
    
    Args:
        csv_path: Path to the CSV file (for display)
        results: List of query result dictionaries
    """
    print("=" * 100)
    print("QUERY RESULT ERROR ANALYSIS")
    print("=" * 100)
    print(f"Input file: {csv_path}")
    print(f"Total rows: {len(results)}")
    print()
    
    # Get all errors
    errors = get_errors_with_ids(results)
    error_count = len(errors)
    success_count = len(results) - error_count
    
    print("-" * 100)
    print("SUMMARY")
    print("-" * 100)
    print(f"Successful queries: {success_count} ({success_count/len(results)*100:.1f}%)")
    print(f"Failed queries:     {error_count} ({error_count/len(results)*100:.1f}%)")
    print()
    
    if not errors:
        print("No errors found. All queries completed successfully!")
        print("=" * 100)
        return
    
    # Categorize errors
    categories = categorize_errors(errors)
    
    print("-" * 100)
    print("ERROR CATEGORIES")
    print("-" * 100)
    for category, items in sorted(categories.items(), key=lambda x: -len(x[1])):
        print(f"  {category}: {len(items)} ({len(items)/error_count*100:.1f}%)")
    print()
    
    # Print all ID-Error pairs
    print("-" * 100)
    print("ALL ID-ERROR PAIRS")
    print("-" * 100)
    print(f"{'Query ID':<12} {'Row':<6} {'Error'}")
    print("-" * 100)
    
    for query_id, original_row, error, query in errors:
        # Truncate long error messages for display
        error_display = error[:70] + "..." if len(error) > 70 else error
        print(f"{query_id:<12} {original_row:<6} {error_display}")
    
    print()
    
    # Print detailed breakdown by category
    print("-" * 100)
    print("DETAILED BREAKDOWN BY CATEGORY")
    print("-" * 100)
    
    for category, items in sorted(categories.items(), key=lambda x: -len(x[1])):
        print(f"\n[{category}] - {len(items)} errors")
        print("-" * 160)
        print(f"{'Query ID':<12} {'Row':<6} {'Query':<90} {'Error'}")
        print("-" * 160)
        
        for query_id, original_row, query, error in items:
            query_display = query[:88] + ".." if len(query) > 90 else query
            error_display = error[:50] + ".." if len(error) > 52 else error
            print(f"{query_id:<12} {original_row:<6} {query_display:<90} {error_display}")
    
    print()
    print("=" * 100)


def main():
    """Main entry point."""
    args = parse_arguments()
    
    # Validate input file exists
    csv_path = Path(args.input_csv)
    if not csv_path.exists():
        print(f"Error: Input CSV file does not exist: {args.input_csv}", file=sys.stderr)
        sys.exit(1)
    
    # Load results
    try:
        results = load_query_results(args.input_csv)
    except Exception as e:
        print(f"Error loading CSV file: {e}", file=sys.stderr)
        sys.exit(1)
    
    if not results:
        print("Error: No data found in CSV file", file=sys.stderr)
        sys.exit(1)
    
    # Print error analysis
    print_error_analysis(args.input_csv, results)


if __name__ == "__main__":
    main()
